/**
 * Returns a translated string. Falls back to Dutch and then to the key.
 * Supports placeholders such as {name} or {year}.
 */
export function translate(key, language = DEFAULT_LANGUAGE, variables = {}) {
  const selectedLanguage = TRANSLATIONS[language] ?? TRANSLATIONS[DEFAULT_LANGUAGE];
  const template = selectedLanguage[key] || TRANSLATIONS[DEFAULT_LANGUAGE][key] || key;

  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, variableName) => {
    return Object.prototype.hasOwnProperty.call(variables, variableName)
      ? String(variables[variableName])
      : match;
  });
}

/** Returns true when a language code is available. */
export function isSupportedLanguage(language) {
  return Object.prototype.hasOwnProperty.call(TRANSLATIONS, language);
}

/** Returns all supported language codes. */
export function getSupportedLanguages() {
  return Object.keys(TRANSLATIONS);
}

/**
 * Applies translations to HTML elements with a data-i18n attribute.
 * Example: <h1 data-i18n="code150"></h1>
 */
export function applyTranslations(language = DEFAULT_LANGUAGE, root = document) {
  const safeLanguage = isSupportedLanguage(language) ? language : DEFAULT_LANGUAGE;
  document.documentElement.lang = safeLanguage;

  root.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    element.textContent = translate(key, safeLanguage);
  });

  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    element.setAttribute("placeholder", translate(key, safeLanguage));
  });

  root.querySelectorAll("[data-i18n-title]").forEach((element) => {
    const key = element.dataset.i18nTitle;
    element.setAttribute("title", translate(key, safeLanguage));
  });
}

export default TRANSLATIONS;
